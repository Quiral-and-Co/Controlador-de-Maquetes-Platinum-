'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('catalan-localization.js','utf8');
const sandbox={window:{},document:{readyState:'loading',addEventListener(){}},Node:{TEXT_NODE:3,ELEMENT_NODE:1},Map,Object,String,RegExp};
vm.runInNewContext(source,sandbox,{filename:'catalan-localization.js'});
const i18n=sandbox.window.JMRI_TC_I18N;
assert.equal(i18n.language,'ca');
assert.equal(i18n.translate('Dispatcher'),'Despatxador');
assert.equal(i18n.translate('Schedule Successors'),'Horaris successors');
assert.equal(i18n.translate('Validation Master Registry'),'Registre mestre de validació');
assert.equal(i18n.translate('System name'),'Identificador JMRI');
assert.equal(i18n.translate('Stop Layout'),'Aturar la maqueta');
assert.equal(i18n.translate('autosave'),'autosave','Do not translate technical substrings inside other words');
assert.equal(i18n.translate('Metge Quiral · System health'),'Metge Quiral · System health');
const html=fs.readFileSync('index.html','utf8'),main=fs.readFileSync('electron/main.cjs','utf8');
assert.match(html,/<html lang="ca">/);
assert.ok(html.includes('catalan-localization.js'),'localization layer must load in the application');
assert.ok(html.includes('Metge Quiral · salut del sistema'),'Metge Quiral diagnostics must remain visible');
assert.ok(main.includes("label: 'Despatxador'"));
assert.ok(main.includes("label: 'Ajuda ràpida en català'"));
assert.ok(main.includes("buttonLabel: 'Obrir'")&&main.includes("buttonLabel: 'Desar'"));
assert.ok(main.includes('METGE QUIRAL'));
console.log('PASS: Catalan localization, dynamic phrase dictionary, technical identifier safety, native dialogs and Metge Quiral help contract');
