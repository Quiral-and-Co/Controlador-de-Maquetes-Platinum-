'use strict';
const assert=require('node:assert/strict');
const p=require('../train-ground-core.js');
let s=p.createState();
assert.equal(s.mode,'ANALOG');
let r=p.setMode(s,'GSMR');assert.equal(r.ok,true);s=r.state;
assert.equal(p.call(s,'Regulació').ok,false);
s=p.register(s).state;assert.equal(s.registered,true);
s=p.configure(s,{trainId:'252-001',selectedFunction:'Circulació'}).state;
s=p.call(s,'Regulació').state;assert.equal(s.callState,'CALLING');
s=p.answer(s).state;assert.equal(s.callState,'CONNECTED');
s=p.transmit(s,'Prova de comunicació').state;assert.equal(s.messages.at(-1).text,'Prova de comunicació');
s=p.press(s,'PTT_ON').state;assert.equal(s.ptt,true);
s=p.press(s,'PTT_OFF').state;assert.equal(s.ptt,false);
s=p.release(s).state;assert.equal(s.callState,'IDLE');
s=p.incoming(s,'Centre de regulació').state;assert.equal(s.callState,'RINGING');
s=p.answer(s).state;assert.equal(s.callState,'CONNECTED');
s=p.press(s,'EMERGENCY').state;assert.ok(s.events.some(e=>e.type==='priority'));
assert.equal(p.setMode(s,'BAD').ok,false);
console.log('Train-ground analog/GSM-R simulation tests passed');
