'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const main=fs.readFileSync('electron/main.cjs','utf8');
const app=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const manager=fs.readFileSync('desktop-window-manager.js','utf8');
const styles=fs.readFileSync('styles.css','utf8');
for(const label of ["label: 'Finestres'","label: 'Ajuda'","Mostrar totes les finestres","Disposar en cascada","Disposar en mosaic","Restaurar disposició inicial","Guia ràpida","Dreceres de teclat","Seguretat i diagnòstics del Metge Quiral"])assert.ok(main.includes(label),'native menu missing '+label);
for(const command of ['windowShowAll','windowMinimizeAll','windowCascade','windowTile','windowRestoreLayout','windowShowEditor','windowShowDispatcher','windowShowTraffic','windowShowSchedules','windowShowOperation','windowShowMetgeQuiral','helpQuick','helpContents','helpShortcuts','helpDiagnostics','helpAbout'])assert.ok(app.includes("command==='"+command+"'"),'missing command handler '+command);
for(const method of ['showAll','minimizeAll','focusWindow','restoreLayout','cascade','tile'])assert.ok(manager.includes(method+'()')||manager.includes(method+'(query)'), 'missing window manager operation '+method);
for(const topic of ['quick','contents','shortcuts','diagnostics','about'])assert.ok(html.includes('data-help-section="'+topic+'"'),'missing help topic '+topic);
for(const tab of ['windows','help'])assert.ok(html.includes('data-ribbon-tab="'+tab+'"')&&html.includes('data-ribbon-page="'+tab+'"'),'missing ribbon page '+tab);
assert.match(app,/JMRI_TC_DESKTOP\?\.focusWindow/);
assert.match(html,/JMRI_TC_ENABLE_DCC=0/);
assert.match(html,/JMRI_TC_SAFETY_VALIDATED=0/);
assert.match(styles,/\.help-dialog::backdrop/);
console.log('PASS: native Finestres/Ajuda menus, ribbon commands, floating-window management and Catalan help topics');
console.log('PASS: safety locks are documented and remain unchanged');
