'use strict';
const assert=require('node:assert/strict');
const a=require('../automation-core.js');
const routes=[{id:'R1',blockIds:['B01','B02','B03']}];
const locomotives=[{id:'L1'}];
const state=a.createState();
const input={id:'H1',name:'Tren matí',routeId:'R1',locomotiveId:'L1',startTime:'08:30',days:[1,2,3,4,5],maxSpeed:12,windowMinutes:2,requiredTurnouts:[{systemName:'LT1',state:'CLOSED',verified:true}]};
assert.equal(a.parseClock('08:30'),510);
assert.equal(a.parseClock('24:00'),null);
assert.equal(a.validateSchedule({...input,startTime:'8:30'},routes,locomotives).ok,false);
assert.equal(a.validateSchedule({...input,maxSpeed:21},routes,locomotives).ok,false);
assert.equal(a.addSchedule(state,input,routes,locomotives).ok,true);
assert.equal(a.addSchedule(state,input,routes,locomotives).ok,false);
const monday=new Date(2026,10,16,8,31,0);
const safe={jmriConnected:true,jmriPower:'ON',bridgeConnected:true,dccArmed:true,sensorDataValid:true,route:routes[0],blockStates:{B01:'OCCUPIED',B02:'FREE',B03:'FREE'},turnoutStates:{LT1:{state:'CLOSED',verified:true}}};
assert.equal(a.evaluateSchedule(state.schedules[0],new Date(2026,10,16,8,29),safe).status,'WAIT');
assert.equal(a.evaluateSchedule(state.schedules[0],monday,safe).status,'READY');
assert.equal(a.evaluateSchedule(state.schedules[0],new Date(2026,10,16,8,34),safe).status,'MISSED');
assert.equal(a.evaluateSchedule(state.schedules[0],new Date(2026,10,17,8,31),safe).status,'WAIT');
assert.equal(a.evaluateSchedule(state.schedules[0],monday,{...safe,blockStates:{...safe.blockStates,B02:'UNKNOWN'}}).status,'BLOCKED');
assert.equal(a.evaluateSchedule(state.schedules[0],monday,{...safe,turnoutStates:{LT1:{state:'THROWN',verified:true}}}).status,'BLOCKED');
assert.equal(a.evaluateSchedule(state.schedules[0],monday,{...safe,jmriPower:'UNKNOWN'}).status,'BLOCKED');
const claimed=a.claimExecution(state,'H1',monday,safe);
assert.equal(claimed.ok,true);
assert.equal(a.claimExecution(state,'H1',monday,safe).ok,false,'same schedule cannot be claimed twice on the same date');
assert.equal(a.completeExecution(state,claimed.execution.id).ok,true);
assert.equal(a.completeExecution(state,claimed.execution.id).ok,false,'completed execution cannot be completed twice');
const nextDay=new Date(2026,10,17,8,31,0);
assert.equal(a.claimExecution(state,'H1',nextDay,safe).ok,true,'schedule can be claimed on a later scheduled day');
assert.equal(a.evaluateSchedule({...state.schedules[0],enabled:false},monday,safe).status,'DISABLED');
console.log('PASS: timetable validation, weekday/window evaluation, fail-safe preflight, verified turnout alignment and duplicate execution protection');
