'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('app.js', 'utf8');
const main = fs.readFileSync('electron/main.cjs', 'utf8');
const preload = fs.readFileSync('electron/preload.cjs', 'utf8');

assert.match(app, /function readPreferredInterfaceMode\(\)/, 'startup interface mode must be loaded from saved preferences');
assert.match(app, /return saved\.interfaceMode==='classic'\?'classic':'modern'/, 'modern interface must be the default when no classic preference exists');
assert.match(app, /if\(\/\[\?&\]nativePanel=\/\.test\(window\.location\.search\|\|''\)\)return 'modern'/, 'detached native module windows must render their panel in modern mode even when the main window prefers classic mode');
assert.match(app, /saved\.interfaceMode=next/, 'manual mode changes must persist as the next startup mode');
const personalization = fs.readFileSync('workspace-personalization.js', 'utf8');
assert.match(personalization, /interfaceMode:'modern'/, 'fresh installations must default to modern mode');
assert.match(personalization, /Mode d’inici del programa/, 'startup mode must be configurable in Personalització');
assert.match(personalization, /\['modern','Modern · cinta d’opcions'\].*\['classic','Clàssic · menús i barres'\]/, 'Personalització must offer modern and classic startup modes');
const modeStart = app.indexOf('function setMode(');
const modeEnd = app.indexOf('window.JMRI_TC_DISPATCHER =', modeStart);
assert.ok(modeStart >= 0 && modeEnd > modeStart, 'mode switch implementation must exist');
const modeSource = app.slice(modeStart, modeEnd);
assert.match(modeSource, /document\.body\?\.classList\?\.toggle\('mode-modern'/);
assert.match(modeSource, /setUiMode\?\.\(next\)/);
assert.doesNotMatch(modeSource, /state\.config\s*=|state\.selectedIds\s*=|state\.selectedLevel\s*=/,
  'switching interface mode must not replace project, selection or active level');
assert.match(preload, /setUiMode:\s*mode\s*=>/);
assert.match(main, /autoHideMenuBar:\s*true/);
assert.match(main, /setMenuBarVisibility\(activeMode === 'classic'\)/, 'native menu must be visible only in classic mode');
assert.match(app, /ribbon\.hidden=next!=='modern'/, 'ribbon visibility must be explicitly synchronized with mode');
assert.match(main, /Menús clàssics/);
assert.match(main, /Menús moderns/);
assert.match(main, /ipcMain\.on\('ui:mode'/);
assert.match(main, /JMRI_TC_ENABLE_DCC:\s*'0'/);
assert.match(main, /JMRI_TC_SAFETY_VALIDATED:\s*'0'/);
assert.match(main, /label: 'Ferrocarril'/, 'Railroad menu must be present in the native menu');
assert.match(main, /Configurar sistema digital/, 'digital-system configuration must be reachable');
assert.match(main, /Estat de la connexió i de la central/, 'connection diagnostics must be available');
assert.match(main, /Aturar tots els trens .*enabled: false/, 'global train stop must remain disabled until fail-safe validation');
assert.match(main, /Activar alimentació de via .*enabled: false/, 'track power must remain physically locked');
assert.match(app, /command==='openCommandStation'/, 'Railroad setup command must open the digital-system panel');
assert.match(app, /command==='showDigitalStatus'/, 'Railroad diagnostics must report read-only status');
assert.match(app, /sortides físiques i DCC: BLOQUEJATS/, 'diagnostics must state the physical-output lock');
console.log('PASS Railroad menu, digital setup navigation, read-only diagnostics and physical-output locks');
console.log('PASS Windows UI mode contract and fail-safe defaults');

assert.match(app, /JMRI_TC_DESKTOP\?\.setMode/);
const manager = fs.readFileSync('desktop-window-manager.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');
assert.match(manager, /let activeMode = null;/, 'initial modern mode must be applied instead of being skipped as already active');
assert.match(manager, /desktop-window-titlebar/);
assert.match(manager, /desktop-taskbar/);
assert.match(styles, /resize:both/);
assert.match(manager, /pointermove/);
assert.match(manager, /openNativePanel/, 'each modern internal window must offer native Windows detachment');
assert.match(manager, /nativePanelKey/, 'detached native windows must render only their selected panel');
assert.match(manager, /onNativeWindowClosed/, 'closing a detached window must restore its internal panel');
assert.match(preload, /openNativePanel:/);
assert.match(preload, /getWorkspaceState:/);
assert.match(app, /publishWorkspaceState\(\)/, 'project changes must synchronize across native panel windows');
assert.match(app, /applyWorkspaceState\(payload\)/, 'detached panel changes must update the shared project state');
const multiMonitor = fs.readFileSync('electron/multimonitor.cjs','utf8');
assert.match(multiMonitor,/let stateRevision = 0;/,'shared workspace must have a monotonic revision');
assert.match(multiMonitor,/payload\.baseRevision !== stateRevision/,'stale workspace writes must be rejected');
assert.match(multiMonitor,/authorizedWindowId/,'workspace publisher identity must be tied to its Electron window');
assert.match(multiMonitor,/persistQueue\.then/,'window-layout persistence must serialize concurrent writes');
assert.match(multiMonitor,/randomUUID\(\) \+ '\.tmp'/,'layout writes must use unique temporary files');
assert.match(app,/baseRevision:workspaceRevision/,'renderer writes must carry their last accepted revision');
assert.match(app,/CONFLICTE DE SINCRONITZACIÓ/,'stale local edits must be surfaced instead of silently overwriting remote data');
const vmrUi=fs.readFileSync('validation-master-registry-ui.js','utf8');
assert.match(vmrUi,/navigator\?\.locks\?\.request/,'VMR persistence must require cross-window exclusive locking');
assert.match(vmrUi,/jmri-tc-vmr:/,'VMR locks must be scoped to the project storage key');
assert.match(vmrUi,/core\.load\(root\.localStorage,snapshot\.storageKey\)/,'VMR transactions must reload the latest persisted state inside the lock');
assert.doesNotMatch(vmrUi,/const persistence=core\.save\(s,root\.localStorage,storageKey\)/,'VMR render must not persist on every refresh');
assert.match(vmrUi,/core\.save\(s,root\.localStorage,snapshot\.storageKey\)/,'VMR mutations must persist inside the exclusive lock');
assert.match(vmrUi,/persistSnapshot\(\{c,s,storageKey\}\)/,'reconciliation changes must be durably persisted through the same transaction');
const vmrCore=fs.readFileSync('validation-master-registry-core.js','utf8');
assert.match(vmrCore,/if\(changed\)state\.updatedAt=nowIso\(now\)/,'VMR reconciliation timestamps must remain stable when no data changes');
assert.match(app,/state\.history=\[\];state\.future=\[\]/,'remote workspace revisions must invalidate stale undo/redo history');
console.log('PASS revisioned workspace synchronization, serialized layout writes and VMR transactional persistence');
assert.match(manager, /leaveModern/);
assert.match(manager, /Tauler de disseny de la maqueta/);
console.log('PASS floating modern desktop windows, taskbar and classic restore contract');

const html = fs.readFileSync('index.html','utf8');
assert.match(html, /id="modernRibbon"/, 'modern mode must provide a real ribbon');
assert.match(html, /data-ribbon-tab="home"/);
assert.match(html, /data-ribbon-page="railroad"/);
assert.match(app, /data-ribbon-command/);
assert.match(app, /function handleAppCommand\(command\)/, 'ribbon actions must share the real command dispatcher');
assert.match(app, /addEventListener\('click',\(\)=>handleAppCommand\(button\.dataset\.ribbonCommand\)\)/);
console.log('PASS modern ribbon tabs and functional command routing');

const workflowHtml=fs.readFileSync('index.html','utf8');
assert.match(workflowHtml,/id="modeEditing"/,'dedicated edit-mode icon must be present');
assert.match(workflowHtml,/id="modeOperation"/,'dedicated operation-mode icon must be present');
assert.match(app,/function setEditingMode\(enabled\)/,'edit mode must have an independent state transition');
assert.match(app,/function setOperationMode\(enabled\)/,'operation mode must have an independent state transition');
assert.match(app,/if\(!editingMode\)\{selectPiece\(id,e\);return;\}/,'track dragging must be disabled outside edit mode while selection remains available');
assert.match(app,/if\(!editingMode\|\|!state\.portMode\)return/,'track connections must be blocked outside edit mode');
assert.match(app,/quiral\.workflow\.modes\.v1/,'workflow modes must persist independently');
assert.match(styles,/\.workflow-mode-btn\.active[^}]*background:\s*#23864b/s,'active workflow icons must have a green background');
console.log('PASS independent edit/operation modes, green active indicators and edit guards');
