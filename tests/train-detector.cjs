'use strict';
const assert=require('node:assert/strict');
const core=require('../train-detector-core');
const now=100000;
const sensors=[{id:'S1',systemName:'LS1',verified:true},{id:'S2',systemName:'LS2',verified:true}];
const block={id:'B1',name:'Tram nord',verified:true,sensorIds:['S1','S2']};
const telemetry={connected:true,sensors:{LS1:4,LS2:4},sensorUpdatedAt:{LS1:now,LS2:now}};
assert.equal(core.sensorState(2),'OCCUPIED');
assert.equal(core.sensorState(4),'FREE');
assert.equal(core.sensorState(0),'UNKNOWN');
assert.equal(core.sensorState(4,true),'OCCUPIED');
assert.equal(core.evaluateBlock(block,sensors,telemetry,now).state,'FREE');
assert.equal(core.evaluateBlock(block,sensors,{...telemetry,sensors:{LS1:2,LS2:4}},now).state,'OCCUPIED');
assert.equal(core.evaluateBlock(block,sensors,{...telemetry,sensors:{LS1:2}},now).state,'UNKNOWN','missing second reading cannot be treated as free or occupied');
assert.equal(core.evaluateBlock(block,sensors,{...telemetry,sensorUpdatedAt:{LS1:now-16000,LS2:now}},now).state,'UNKNOWN','stale readings fail closed');
assert.equal(core.evaluateBlock(block,sensors,{...telemetry,connected:false},now).state,'UNKNOWN','disconnect invalidates occupancy');
assert.equal(core.evaluateBlock({...block,verified:false},sensors,telemetry,now).state,'UNKNOWN','unverified block remains unknown');
assert.equal(core.evaluateBlock(block,[{...sensors[0],verified:false},sensors[1]],telemetry,now).state,'UNKNOWN','unverified detector remains unknown');
assert.equal(core.evaluateBlock({...block,sensorIds:[]},sensors,telemetry,now).state,'UNKNOWN','block without detectors remains unknown');
assert.equal(core.evaluateBlock(block,sensors,{...telemetry,sensors:{LS1:'nonsense',LS2:4}},now).state,'UNKNOWN','unknown protocol state remains unknown');
const config={levels:[{id:1,name:'Nivell 1',sensors,blocks:[block,{id:'B2',name:'Sense verificació',verified:false,sensorIds:['S1']}]}]};
const rows=core.inspect(config,telemetry,now);
assert.equal(rows.length,2);
assert.equal(rows[0].state,'FREE');
assert.equal(rows[0].sensorReadings[0].state,'FREE');
assert.equal(rows[1].state,'UNKNOWN');
assert.equal(rows[1].sensorReadings[0].state,'FREE','raw sensor feedback remains visible while block verification is pending');
console.log('PASS: detector occupancy evaluation, freshness, inversion and fail-safe unknown states');
