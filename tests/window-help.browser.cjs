'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const http=require('node:http');
const path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json'};
const server=http.createServer((req,res)=>{const pathname=decodeURIComponent(new URL(req.url,'http://127.0.0.1').pathname),file=path.resolve(root,'.'+pathname);if(!file.startsWith(root+path.sep)&&file!==path.join(root,'index.html')){res.writeHead(403).end();return;}fs.readFile(file,(err,data)=>{if(err){res.writeHead(404).end(String(err));return;}res.writeHead(200,{'content-type':mime[path.extname(file)]||'application/octet-stream'});res.end(data);});});
(async()=>{await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));let browser,context;try{browser=await chromium.launch({headless:true,args:['--no-sandbox']});context=await browser.newContext();const page=await context.newPage();await page.goto('http://127.0.0.1:'+server.address().port+'/index.html');await page.waitForFunction(()=>window.JMRI_TC_DESKTOP&&window.JMRI_TC_DESKTOP.getWindows().length>0);
await page.locator('[data-ribbon-tab="windows"]').click();
await page.locator('[data-ribbon-command="windowCascade"]').click();
assert.ok(await page.locator('.desktop-window').first().evaluate(el=>parseInt(el.style.left,10)>=0));
await page.locator('[data-ribbon-command="windowMinimizeAll"]').click();
assert.equal(await page.locator('.desktop-window:not([hidden])').count(),0);
await page.locator('[data-ribbon-command="windowShowAll"]').click();
assert.ok(await page.locator('.desktop-window:not([hidden])').count()>0);
await page.locator('[data-ribbon-command="windowRestoreLayout"]').click();
await page.locator('[data-ribbon-tab="help"]').click();
await page.locator('[data-ribbon-command="helpQuick"]').click();
assert.equal(await page.locator('#helpDialog').evaluate(el=>el.open),true);
assert.equal(await page.locator('[data-help-section="quick"]').isVisible(),true);
await page.locator('[data-help-topic="contents"]').click();
assert.equal(await page.locator('[data-help-section="contents"]').isVisible(),true);
assert.equal(await page.locator('[data-help-section="quick"]').isVisible(),false);
await page.locator('[data-help-topic="shortcuts"]').click();
assert.equal(await page.locator('[data-help-section="shortcuts"] table tbody tr').count(),8);
await page.locator('[data-help-topic="diagnostics"]').click();
await page.locator('#helpRunMetgeQuiral').click();
assert.equal(await page.locator('#helpDialog').evaluate(el=>el.open),false);
assert.ok(await page.locator('#metgeQuiralStatus').isVisible());
await page.locator('#helpDialogClose').click().catch(()=>{});
assert.equal(await page.locator('#helpDialog').evaluate(el=>el.open),false);
console.log('PASS: browser window actions (cascade/minimize/show/restore) and Catalan help dialog navigation');
}finally{await context?.close().catch(()=>{});await browser?.close().catch(()=>{});await new Promise(resolve=>server.close(resolve));}})().catch(e=>{console.error(e);process.exitCode=1;});
