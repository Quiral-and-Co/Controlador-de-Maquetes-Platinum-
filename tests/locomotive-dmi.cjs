const assert=require('node:assert/strict');
const core=require('../locomotive-dmi-core.js');
assert.equal(core.validateCalibration(160).ok,true);
assert.equal(core.validateCalibration(0).ok,false);
assert.equal(core.validateCalibration(501).ok,false);
assert.equal(core.stepToKmh(63,126),63);
assert.equal(core.stepToKmh(126,160),160);
assert.equal(core.kmhToStep(80,160),63);
assert.equal(core.kmhToStep(300,160),126);
assert.equal(core.needleAngle(0,160),-135);
assert.equal(core.needleAngle(160,160),135);
assert.equal(core.normalizeAspect({computedAspect:'VIA_LIBRE'}), 'via libre');
assert.deepEqual(core.signalChain([{id:'S1',nextSignalId:'S2'},{id:'S2',nextSignalId:'S3'},{id:'S3'}],{blockIds:[]}).map(s=>s.id),['S1','S2']);
assert.equal(core.distanceLabel(850),'850 m');
assert.equal(core.distanceLabel(1250),'1.25 km');
assert.equal(core.distanceLabel(null),'Sense telemetria');
assert.equal(core.turnoutLabel(2),'Directa');
assert.equal(core.turnoutLabel(4),'Desviada');
assert.equal(core.turnoutLabel('UNKNOWN'),'Desconeguda');
assert.equal(core.functionLabel(0),'F0 · Llums');
assert.equal(core.functionLabel(32),'F32');
console.log('PASS: DMI speed calibration, km/h mapping, needle scale, signal chain, dynamic distance fallback, turnout position and F0–F32 labels');
