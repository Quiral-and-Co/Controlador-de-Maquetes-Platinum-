'use strict';
const assert=require('node:assert/strict');
const core=require('../virtual-contact-core.js');
const blocks=[{id:'B1',verified:true,lengthMm:1000},{id:'B2',verified:false,lengthMm:1000}];
const sensors=[{systemName:'S1',verified:true},{systemName:'S2',verified:false}];
const base={id:'VC1',blockId:'B1',name:'Frenada',kind:'VIRTUAL',enabled:true,action:'BRAKE_REQUEST'};
let r=core.normalizeDefinition({...base,trigger:{type:'DISTANCE',distanceMm:500}},blocks,sensors);
assert.equal(r.ok,true);
assert.equal(r.contact.address,null);
assert.equal(core.evaluate(r.contact,{positionEstimate:{blockId:'B1',positionMm:510,verified:true,profileVerified:true}}).active,true);
assert.equal(core.evaluate(r.contact,{positionEstimate:{blockId:'B1',positionMm:510,verified:false,profileVerified:true}}).state,'UNKNOWN');
assert.equal(core.evaluate(r.contact,{positionEstimate:{blockId:'B1',positionMm:510,verified:true,profileVerified:false}}).state,'UNKNOWN');
assert.equal(core.normalizeDefinition({...base,blockId:'B2',trigger:{type:'DISTANCE',distanceMm:500}},blocks,sensors).ok,false);
assert.equal(core.normalizeDefinition({...base,trigger:{type:'DISTANCE',distanceMm:1000}},blocks,sensors).ok,false);
const timed=core.normalizeDefinition({...base,trigger:{type:'TIME',seconds:30}},blocks,sensors).contact;
assert.equal(core.evaluate(timed,{positionEstimate:{blockId:'B1',elapsedSeconds:31,verified:true,profileVerified:true}}).active,true);
const logic=core.normalizeDefinition({...base,action:'LOGIC_EVENT',trigger:{type:'LOGIC',operator:'AND',conditions:[{systemName:'S1',state:'ACTIVE'},{systemName:'S1',state:'ACTIVE'}]}},blocks,sensors);
assert.equal(logic.ok,true);
assert.equal(core.evaluate(logic.contact,{sensorStates:{S1:'ACTIVE'}}).active,true);
assert.equal(core.evaluate(logic.contact,{sensorStates:{S1:'UNKNOWN'}}).state,'UNKNOWN');
assert.equal(core.normalizeDefinition({...base,trigger:{type:'LOGIC',operator:'AND',conditions:[{systemName:'S2',state:'ACTIVE'}]}},blocks,sensors).ok,false);
console.log('Contactes virtuals: proves superades.');
