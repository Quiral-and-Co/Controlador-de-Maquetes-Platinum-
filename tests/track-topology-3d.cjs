'use strict';
const assert=require('node:assert/strict');
const topology=require('../track-topology-3d-core.js');
const level={id:1,elevationMm:0};
const flat={id:'FLAT',type:'straight',zMm:12};
assert.equal(topology.portZ(flat,level,'A'),12);
assert.equal(topology.portZ(flat,level,'B'),12);
const ramp={id:'RAMP',type:'straight',zMm:12,verticalGeometry:{zStartMm:12,zEndMm:122}};
assert.equal(topology.portZ(ramp,level,'A'),12);
assert.equal(topology.portZ(ramp,level,'B'),122);
const next={id:'NEXT',type:'straight',zMm:122};
const aligned=topology.gap3D({x:280,y:100,zMm:topology.portZ(ramp,level,'B')},{x:280,y:100,zMm:topology.portZ(next,level,'A')});
assert.deepEqual(aligned,{valid:true,distanceMm:0,horizontalMm:0,verticalMm:0,deltaZMm:0});
const mismatch=topology.gap3D({x:280,y:100,zMm:0},{x:280,y:100,zMm:110});
assert.equal(mismatch.valid,true);
assert.equal(mismatch.horizontalMm,0);
assert.equal(mismatch.verticalMm,110);
assert.equal(mismatch.distanceMm,110);
const diagonal=topology.gap3D({x:0,y:0,zMm:0},{x:3,y:4,zMm:12});
assert.equal(diagonal.horizontalMm,5);
assert.equal(diagonal.distanceMm,13);
const legacy={id:'LEGACY',type:'straight'};
assert.equal(topology.portZ(legacy,{id:2,elevationMm:110},'A'),110,'Legacy pieces without zMm inherit their level elevation');
assert.ok(Number.isNaN(topology.portZ({id:'BAD',type:'straight',zMm:'not-a-number'},level,'A')),'Invalid explicit Z must not silently fall back');
assert.equal(topology.gap3D({x:0,y:0,zMm:0},{x:0,y:0,zMm:undefined}).valid,false,'Missing endpoint elevation must fail closed');
assert.deepEqual(ramp,{id:'RAMP',type:'straight',zMm:12,verticalGeometry:{zStartMm:12,zEndMm:122}},'The audit helpers must not mutate pieces');
console.log('PASS 3D topology: endpoint elevation, vertical-ramp endpoints, level fallback, XYZ distance and fail-closed invalid elevations');
