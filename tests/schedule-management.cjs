'use strict';
const assert=require('node:assert/strict');
const s=require('../schedule-management-core.js');
const routes=[{id:'R1',blockIds:['B1','B2']},{id:'R2',blockIds:['B2','B3']}],locos=[{id:'L1'},{id:'L2'}];
const state=s.ensure({});
const base={id:'S1',name:'Tren matí',routeId:'R1',locomotiveId:'L1',startTime:'08:30',days:[1,2,3,4,5],maxSpeed:12,windowMinutes:2};
assert.equal(s.add(state,base,routes,locos).ok,true);
assert.equal(s.add(state,{...base,id:'S2',name:'Tren tarda',routeId:'R2',locomotiveId:'L2'},routes,locos).ok,true);
assert.equal(s.add(state,{...base,id:'S3',name:'Tren nit'},routes,locos).ok,true);
assert.equal(s.validate({...base,startTime:'8:30'},routes,locos).ok,false);
assert.equal(s.validate({...base,maxSpeed:21},routes,locos).ok,false);
assert.equal(s.validate({...base,days:[1,1]},routes,locos).ok,false);
assert.equal(s.setSuccessors(state,'S1',['S2']).ok,true);
assert.equal(s.setSuccessors(state,'S2',['S1']).ok,false);
assert.equal(s.setSuccessors(state,'S1',['S1']).ok,false);
assert.equal(s.setSuccessors(state,'S1',['missing']).ok,false);
assert.equal(s.evaluate({...base,enabled:false},new Date(2026,10,16,8,31)).status,'DISABLED');
assert.equal(s.evaluate(base,new Date(2026,10,16,8,29)).status,'WAIT');
assert.equal(s.evaluate(base,new Date(2026,10,16,8,31)).status,'DUE');
assert.equal(s.evaluate(base,new Date(2026,10,16,8,40)).status,'MISSED');
assert.equal(s.update(state,'S1',{...base,name:'Tren matí editat'},routes,locos).ok,true);
assert.equal(s.remove(state,'S2').ok,true);
assert.deepEqual(state.schedules.find(x=>x.id==='S1').successorIds,[]);
console.log('PASS: schedule CRUD, validation, successor graph, cycle prevention and non-executing timetable preview');
